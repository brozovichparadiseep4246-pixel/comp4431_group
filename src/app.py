MODE_KIMI = "Online · RAG"
MODE_LOCAL = "Local · Qwen + LoRA"


def _mode(v: str) -> str:
    return "local" if v == MODE_LOCAL else "kimi"


def voice_action(index: int):
    return gr.HTML(
        f'<button type="button" class="read-aloud-action" '
        f'data-reply-index="{index}">Read aloud</button>',
        render=False,
    )


def respond(message: str, history: list, mode: str):
    """Stream text only; audio is generated through a message option."""
    message = (message or "").strip()
    if not message:
        yield history or [], "", "idle"
        return
    history = (history or []) + [{"role": "user", "content": message}]
    m = _mode(mode)
    if m == "local":
        pending = thinking_message(
            "Thinking with the local model...",
            "Checking course sources and preparing a CPU response. This may take a little longer.",
        )
    else:
        pending = thinking_message(
            "Thinking...",
            "Checking course sources and preparing your answer.",
        )
    yield history + [pending], "", "thinking"
    partial = ""
    try:
        gen, sources, web_used = bot.chat(message, stream=True, model_mode=m)
        for delta in gen:
            if not delta:
                continue
            partial += delta
            yield history + [{"role": "assistant", "content": partial}], "Writing your answer...", "speaking"
        if not partial.strip():
            raise RuntimeError("The model returned an empty response. Please try again.")
    except Exception as e:
        error = f"Unable to complete the request: {e}"
        reply = f"{partial}\n\n{error}" if partial else error
        yield history + [{"role": "assistant", "content": reply}], error, "idle"
        return
    history = history + [{
        "role": "assistant",
        "content": [partial, voice_action(len(history))],
    }]
    if sources is None:
        # 固定话术回复: 根据内容区分状态提示
        if '已记录你的背景' in partial:
            status = f"Student profile: {bot.profile_text()}"
        elif '请先告诉我' in partial:
            status = "Please share your major and year for personalized advice."
        elif '抱歉，我是 CourseMate' in partial:
            status = "Outside scope. CourseMate focuses on academic advising."
        else:
            status = "Ready for your next question."
    elif m == "local":
        status = "Answer generated by local Qwen + LoRA."
    elif web_used and sources:
        srcs = ", ".join(sorted({c.source for c in sources}))
        status = f"Sources: {srcs} + web search. Verify online information."
    elif web_used:
        status = "Based on web search. Verify information with official sources."
    elif sources:
        srcs = ", ".join(sorted({c.source for c in sources}))
        status = f"Knowledge sources: {srcs}"
    else:
        status = "No matching sources found. Check official course information."
    yield history, status, "happy"


def transcribe_to_input(audio_path, draft: str):
    """Keep the conversation unchanged and put the transcript in the composer."""
    if not audio_path:
        yield gr.skip(), "Record or upload audio to insert a transcript.", "idle"
        return
    yield gr.skip(), "Transcribing your audio...", "thinking"
    try:
        text = transcribe(audio_path)
    except Exception as e:
        yield gr.skip(), f"Transcription failed: {e}", "idle"
        return
    if not text:
        yield gr.skip(), "No speech detected. Please try again.", "idle"
        return
    combined = f"{draft.rstrip()}\n{text}" if draft and draft.strip() else text
    yield combined, "Transcript inserted. Edit your question, then press Send.", "idle"


def read_aloud(history: list, request: str):
    """Generate audio for the selected reply, embedded in that same message."""
    history = history or []
    value = str(request)
    if not value.startswith("read-aloud:"):
        yield gr.skip(), gr.skip(), gr.skip()
        return
    try:
        index = int(value.split(":")[1])
    except ValueError:
        yield gr.skip(), "Invalid voice reply selection.", "idle"
        return
    if not 0 <= index < len(history) or history[index]["role"] != "assistant":
        yield gr.skip(), "That reply is no longer available.", "idle"
        return
    message = history[index]
    content = message["content"]
    parts = content if isinstance(content, list) else [content]
    # Gradio returns normalized content dictionaries on subsequent events.
    text = next((p if isinstance(p, str) else p.get("text", "")
                 for p in parts if isinstance(p, str)
                 or isinstance(p, dict) and p.get("type") == "text"), "")
    if not text.strip():
        yield gr.skip(), "This reply has no text to read.", "idle"
        return
    if any(isinstance(p, gr.Audio)
           or isinstance(p, dict) and ("path" in p or p.get("type") == "file"
                                       or p.get("component") == "audio") for p in parts):
        yield gr.skip(), "Use the audio player in this reply to listen again.", "idle"
        return
    pending = thinking_message(
        "Preparing this voice reply...",
        "Generating audio only for the answer you selected.",
    )["content"]
    working = list(history)
    working[index] = {**message, "content": [text, pending]}
    yield list(working), "", "thinking"
    path = synthesize(text)
    if not path:
        working[index] = {
            **message,
            "content": [text, "Audio could not be generated. Please try Read aloud again.",
                        voice_action(index)],
        }
        yield working, "Voice generation failed. Your text answer is unchanged.", "idle"
        return
    working[index] = {
        **message,
        # A file message plays in the browser without decoding MP3 on every chat turn.
        "content": [text, {"path": path, "alt_text": "Voice reply"}],
    }
    yield working, "Voice reply ready. Use its player to listen again.", "happy"


def clear_all():
    bot.reset()
    return [], "", "idle"


